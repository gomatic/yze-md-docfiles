package docfiles_test

// The generated-file exemption, which is the one way out of this rule and so
// the one place an evasion is worth the most. Every test here is a shape that
// silenced a whole document by claiming an authorship no generator had made.

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

// TestAGeneratedClaimMustBeTheWholeLineInAComment pins the margins the claim
// may sit in. They were once "any run of non-word characters", chosen to
// consume a comment delimiter of any shape — and markdown's list markers,
// blockquote marker and backticks are all non-word characters too. A document
// LISTING the conventional markers, quoting one, or showing one in a code span
// exempted itself from the whole rule, file finding included: the one-line,
// audit-trail-free opt-out the claim pattern exists to prevent, restored by the
// pattern itself.
func TestAGeneratedClaimMustBeTheWholeLineInAComment(t *testing.T) {
	t.Parallel()

	for name, header := range map[string]string{
		"list item":       "- @generated",
		"asterisk item":   "* @generated",
		"blockquote":      "> @generated",
		"code span":       "`@generated`",
		"list and span":   "- `@generated`",
		"prose around it": "This file is @generated by hand",
	} {
		assert.Len(t, analyze(t, "api.md", header+"\n\n## Changelog\n"), 1,
			"%s is not a generator's claim of authorship", name)
	}

	for name, header := range map[string]string{
		"html comment": "<!-- @generated -->",
		"slash":        "// @generated",
		"hash":         "# @generated",
		"semicolon":    "; @generated",
		"rst comment":  ".. @generated",
		"block":        "/* Code generated by tool. DO NOT EDIT. */",
		"bare":         "@generated",
	} {
		assert.Empty(t, analyze(t, "api.md", header+"\n\n## Changelog\n"),
			"%s is a generator's claim", name)
	}
}

// TestAGeneratedClaimInsideAFenceDoesNotExempt pins the same opt-out reached
// through the other door. The header used to be read as raw lines while every
// other reader used the block model, so a document DEMONSTRATING a generated
// header — three lines of an ordinary tutorial — silenced every finding in
// itself.
func TestAGeneratedClaimInsideAFenceDoesNotExempt(t *testing.T) {
	t.Parallel()

	fenced := "# Docs\n\n```go\n// Code generated by mockgen. DO NOT EDIT.\n```\n\n## Changelog\n"

	assert.Len(t, analyze(t, "api.md", fenced), 1, "the claim is being shown, not made")
}

// TestAGeneratedClaimIsFoundBehindAByteOrderMark pins that the two readers of a
// document's first line agree. The heading scan stripped the mark and the
// generated-claim scan did not, so a generated file saved by a Windows editor
// had its claim hidden behind an invisible character on exactly the line the
// claim has to be on — and was reported as hand-maintained.
func TestAGeneratedClaimIsFoundBehindAByteOrderMark(t *testing.T) {
	t.Parallel()

	assert.Empty(t, analyze(t, "api.md", "\ufeff<!-- @generated -->\n\n## Changelog\n"))
}
